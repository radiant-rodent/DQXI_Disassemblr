#!/usr/bin/env python3
"""Game versions: work on the retail game or on a patched one (the English translation).

The project's data was extracted from the retail Japanese cartridge.  A *version* is that game
with a patch applied (today: the English translation, `en`).  Only the files the patch changes
are stored per version; switching swaps exactly those files in place, so every tool and DQXI
Studio read the chosen version without knowing about versions at all.

    python -m tools.game_version status                 # active version, what each one changes
    python -m tools.game_version use en                 # switch to the English game
    python -m tools.game_version use original           # back to the retail game
    python -m tools.game_version import en              # (re)import after the patch changed
    python -m tools.game_version import en --from path/to/DQXI_EN.dq11patch
    python -m tools.game_version functions [--json]     # native functions the patch changes

Sources an import accepts (`--from`, default: the translation repository's published patch):
  *.dq11patch            the translation's browser patch (deltas against your own retail ROM)
  *.zip / folder         a Luma3DS LayeredFS export (luma/titles/<title id>/romfs + code.bin)
  *.3ds                  a patched cartridge image (slow: every RomFS file is compared)

What a version tracks (all paths relative to the project root):
  game_data/romfs/...    the changed RomFS files (packs, fonts, BCH)
  game_data/packs/...    the changed / new / removed PACK members (+ _pack.json)
  game_data/arcs/...     the changed SARC members (+ _arc.json)
  game_assets/...        textures, layouts, tables, scripts, models, fonts, text banks derived
                         from the changed members, regenerated by the project's own converters
  asm/...                the disassembly files whose instructions changed
  mod/romfs, mod/code    the mod workspace is per version (stashed in versions/<name>/mod)

The native executable of a version is versions/<name>/code/code.decompressed.bin and
versions/<name>/code_changes.json lists every changed function, code cave and data run with
the original and patched disassembly (shown and editable in DQXI Studio's Code section,
edited with `python -m tools.code_edit`).  original/ always stays the retail baseline.

Switching never overwrites a tracked file that was changed by hand: it stops and lists them
(`--force` overwrites).  An interrupted switch is finished by running the same command again.
"""
