def status_dict() -> dict:
    st = state()
    out = {"active": active(), "switching_to": st.get("switching_to"), "versions": []}
    cfg = sources()
    for n in installed() + [n for n in cfg if n not in installed()]:
        item = {"name": n, "installed": n in installed()}
        if n == ORIGINAL:
            item["label"] = "Original (retail Japanese)"
        elif item["installed"]:
            m = load_manifest(n)
            item.update(label=m.get("label", n), imported_at=m.get("imported_at"),
                        files=len(m["files"]), romfs=len(m.get("romfs_changed", [])), code=m.get("code"),
                        patch_version=m.get("source", {}).get("patch_version"))
            src = Path(m.get("source", {}).get("path", ""))
            cur = sha_file(src) if src.is_file() else None
            item["source"] = str(src)
            item["outdated"] = bool(cur and cur != m.get("source", {}).get("source_sha256"))
        else:
            item["label"] = cfg[n].get("label", n)
            item["source"] = cfg[n].get("source")
            item["available"] = Path(cfg[n].get("source", "")).exists()
        out["versions"].append(item)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")
    s = sub.add_parser("status", help="active version and what each version changes")
    s.add_argument("--json", action="store_true")
    u = sub.add_parser("use", help="switch the project to a version")
    u.add_argument("name")
    u.add_argument("--force", action="store_true", help="overwrite tracked files changed by hand")
    i = sub.add_parser("import", help="(re)import a patched version")
    i.add_argument("name")
    i.add_argument("--from", dest="source", type=Path)
    i.add_argument("--label")
    i.add_argument("--use", action="store_true", help="switch to it afterwards")
    f = sub.add_parser("functions", help="native functions a version changes")
    f.add_argument("name", nargs="?")
    f.add_argument("--json", action="store_true")
    sub.add_parser("active", help="print the active version name")
    args = ap.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    try:
        if args.cmd in (None, "status"):
            st = status_dict()
            if getattr(args, "json", False):
                print(json.dumps(st, indent=1))
                return 0
            print(f"active: {st['active']}" + (f"  (unfinished switch to {st['switching_to']!r}: run `use` again)" if st["switching_to"] else ""))
            for v in st["versions"]:
                mark = "*" if v["name"] == st["active"] else " "
                line = f" {mark} {v['name']:<10} {v['label']}"
                if v.get("installed") and v["name"] != ORIGINAL:
                    c = v.get("code") or {}
                    line += (f"  [{v['romfs']} RomFS files, {v['files']} tracked files, "
                             f"{c.get('functions', 0)} functions + {c.get('caves', 0)} caves changed; "
                             f"imported {v['imported_at']}]")
                    if v.get("outdated"):
                        line += "\n              patch file changed since the import: run `import " + v["name"] + "`"
                elif not v.get("installed"):
                    line += f"  (not imported; source {'found' if v.get('available') else 'missing'}: {v.get('source')})"
                print(line)
        elif args.cmd == "active":
            print(active())
        elif args.cmd == "use":
            switch(args.name, force=args.force)
        elif args.cmd == "import":
            import_version(args.name, args.source, args.label, args.use)
        elif args.cmd == "functions":
            ch = code_changes(args.name or (active() if active() != ORIGINAL else "en"))
            if args.json:
                print(json.dumps(ch, indent=1))
                return 0
            for fn in ch.get("functions", []):
                print(f"{fn['address']:08X} {fn['kind']:<8} {fn['changed_bytes']:>5} B  {fn['name']}")
            for c in ch.get("caves", []):
                print(f"{c['address']:08X} cave     {c['size']:>5} B  {c['name']}  {c.get('note', '')}")
            print(f"{len(ch.get('functions', []))} functions, {len(ch.get('caves', []))} caves, "
                  f"{len(ch.get('data', []))} data runs")
    except VersionError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


