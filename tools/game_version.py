class VersionError(RuntimeError):
    pass


# --------------------------------------------------------------------------- small helpers
def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha_file(path: Path) -> str | None:
    if not path.is_file():
        return None
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _now() -> str:
    return _dt.datetime.now().replace(microsecond=0).isoformat()


def _read_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default


def _write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(value, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def put_blob(data: bytes) -> str:
    digest = sha(data)
    path = STORE / digest[:2] / digest
    if not path.is_file():
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_bytes(data)
        os.replace(tmp, path)
    return digest


def blob_path(digest: str) -> Path:
    return STORE / digest[:2] / digest


def _place(rel: str, digest: str | None) -> None:
    """Make ROOT/rel hold blob `digest` (None: the file does not exist in that version)."""
    dst = ROOT / rel
    if digest is None:
        if dst.is_file():
            dst.unlink()
        return
    src = blob_path(digest)
    if not src.is_file():
        raise VersionError(f"version store is missing blob {digest} for {rel}")
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_name(dst.name + ".gvtmp")
    shutil.copyfile(src, tmp)
    os.replace(tmp, dst)


def _translate_import():
    """dq11tool (the translation's own code) for BLZ and ROM images; read-only use."""
    if str(TRANSLATE) not in sys.path:
        sys.path.insert(0, str(TRANSLATE))
    import dq11tool  # noqa: F401
    return dq11tool


# --------------------------------------------------------------------------- state
def sources() -> dict:
    cfg = dict(DEFAULT_SOURCES)
    cfg.update(_read_json(SOURCES, {}))
    return cfg


def manifest_path(name: str) -> Path:
    return VERSIONS / name / "version.json"


def load_manifest(name: str) -> dict:
    if name == ORIGINAL:
        m = _read_json(manifest_path(ORIGINAL), {})
        m.setdefault("name", ORIGINAL)
        m.setdefault("label", "Original (retail Japanese)")
        m.setdefault("files", {})
        return m
    m = _read_json(manifest_path(name), None)
    if m is None:
        raise VersionError(f"version {name!r} is not imported (python -m tools.game_version import {name})")
    return m


def installed() -> list[str]:
    names = [ORIGINAL]
    if VERSIONS.is_dir():
        for p in sorted(VERSIONS.iterdir()):
            if p.name not in (ORIGINAL, "_store") and (p / "version.json").is_file():
                names.append(p.name)
    return names


def state() -> dict:
    s = _read_json(STATE, {})
    s.setdefault("active", ORIGINAL)
    return s


def active() -> str:
    """The active version's name ('original' when nothing was ever switched)."""
    env = os.environ.get("DQXI_GAME_VERSION")
    if env:
        return env
    return state()["active"]


def code_path(name: str | None = None) -> Path:
    """Decompressed code.bin of a version (the retail one for 'original')."""
    name = name or active()
    if name == ORIGINAL:
        return RETAIL_CODE
    p = VERSIONS / name / "code" / "code.decompressed.bin"
    return p if p.is_file() else RETAIL_CODE


def code_changes(name: str | None = None) -> dict:
    name = name or active()
    if name == ORIGINAL:
        return {}
    return _read_json(VERSIONS / name / "code_changes.json", {})


def expected_code(name: str | None = None) -> dict:
    """What tools.build must reproduce for a version: {sha256, size, compressed_sha256|None}."""
    name = name or active()
    if name == ORIGINAL:
        return {}
    m = load_manifest(name)
    return m.get("code") or {}


def romfs_overrides(name: str | None = None) -> dict[str, Path]:
    """RomFS path ('/a/b.pack') -> file holding the version's bytes (for exporters)."""
    name = name or active()
    if name == ORIGINAL:
        return {}
    m = load_manifest(name)
    out = {}
    for rel, digest in m.get("files", {}).items():
        if rel.startswith("game_data/romfs/") and digest:
            out["/" + rel[len("game_data/romfs/"):]] = blob_path(digest)
    return out


# --------------------------------------------------------------------------- switching
def _expected(rel: str, name: str, manifests: dict) -> str | None:
    m = manifests[name]
    if rel in m["files"]:
        return m["files"][rel]
    return manifests[ORIGINAL]["files"].get(rel)


def switch(target: str, force: bool = False, quiet: bool = False) -> dict:
    """Swap the tracked files from the active version to `target`."""
    names = installed()
    if target not in names:
        raise VersionError(f"unknown version {target!r}; installed: {', '.join(names)}")
    st = state()
    current = st["active"]
    resuming = st.get("switching_to")
    manifests = {n: load_manifest(n) for n in {ORIGINAL, current, target, resuming or ORIGINAL}}
    if current == target and not resuming:
        if not quiet:
            print(f"already on {target!r}")
        return {"active": target, "changed": 0}
    tracked = set(manifests[ORIGINAL]["files"])
    for n in (current, target):
        tracked |= set(manifests[n]["files"])

    # files changed by hand since the last switch: never overwrite them silently
    conflicts = []
    for rel in sorted(tracked):
        have = sha_file(ROOT / rel)
        ok = {_expected(rel, current, manifests), _expected(rel, target, manifests)}
        if resuming:
            ok.add(_expected(rel, resuming, manifests))
        if have not in ok:
            conflicts.append(rel)
    if conflicts and not force:
        lines = "\n  ".join(conflicts[:40])
        more = f"\n  ... and {len(conflicts) - 40} more" if len(conflicts) > 40 else ""
        raise VersionError(
            f"{len(conflicts)} tracked file(s) were changed since version {current!r} was put in place:\n  "
            f"{lines}{more}\nRegenerate them, put your edits in mod/, or rerun with --force to overwrite.")

    _write_json(STATE, {**st, "active": current, "switching_to": target, "since": _now()})
    changed = 0
    for rel in sorted(tracked):
        want = _expected(rel, target, manifests)
        if sha_file(ROOT / rel) != want:
            _place(rel, want)
            changed += 1
    _swap_mod(current, target)
    _write_json(STATE, {"active": target, "since": _now()})
    _refresh_derived(quiet)
    if not quiet:
        print(f"switched {current!r} -> {target!r}: {changed:,} file(s) swapped, mod workspace swapped")
    return {"active": target, "changed": changed}


def _refresh_derived(quiet: bool) -> None:
    """Files built from the text banks (what NPCs say, chapter summaries) must follow the active
    language; npc_talks.json once kept showing the Japanese summaries after switching to English."""
    import subprocess
    try:
        r = subprocess.run([sys.executable, str(ROOT / "tools" / "npc_talk.py")], cwd=ROOT,
                           capture_output=True, text=True, timeout=300)
        if r.returncode != 0 and not quiet:
            print("warning: npc_talks.json not regenerated:", (r.stderr or r.stdout)[-300:])
    except Exception as exc:  # a failed refresh must not undo the switch
        if not quiet:
            print(f"warning: npc_talks.json not regenerated: {exc}")


def _swap_mod(current: str, target: str) -> None:
    if current == target:
        return
    out = VERSIONS / current / "mod"
    inn = VERSIONS / target / "mod"
    for part in MOD_STASHED:
        live = MOD / part
        if live.exists() and any(live.rglob("*")):
            dst = out / part
            if dst.exists():
                shutil.rmtree(dst)
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(live), str(dst))
        elif live.exists():
            shutil.rmtree(live)
        src = inn / part
        if src.exists():
            shutil.move(str(src), str(live))
    (MOD / "romfs").mkdir(parents=True, exist_ok=True)


# --------------------------------------------------------------------------- reading a patch
def _blz():
    _translate_import()
    from dq11tool import blz
    return blz


def _apply_delta(src: bytes, ops: bytes, size: int) -> bytes:
    out = bytearray()
    pos = prev_end = 0

    def varint():
        nonlocal pos
        v = shift = 0
        while True:
            b = ops[pos]
            pos += 1
            v |= (b & 0x7F) << shift
            shift += 7
            if b < 0x80:
                return v

    while len(out) < size:
        v = varint()
        if v & 1:
            out += ops[pos:pos + (v >> 1)]
            pos += v >> 1
        else:
            z = varint()
            start = prev_end + (-(z + 1 >> 1) if z & 1 else z >> 1)
            out += src[start:start + (v >> 1)]
            prev_end = start + (v >> 1)
    return bytes(out)


def read_dq11patch(path: Path) -> tuple[dict[str, bytes], bytes | None, dict]:
    raw = gzip.open(path).read()
    if raw[:8] != b"DQ11PTCH":
        raise VersionError(f"{path} is not a .dq11patch")
    hl = struct.unpack("<I", raw[8:12])[0]
    header = json.loads(raw[12:12 + hl])
    data = raw[12 + hl:]
    if header.get("format") != 1:
        raise VersionError(f"unsupported .dq11patch format {header.get('format')}")
    blz = _blz()
    files: dict[str, bytes] = {}
    code = None
    for e in header["files"]:
        p = e["path"]
        if p == "exefs:.code":
            src_file = RETAIL_CODE_Z
        elif p.startswith("exefs:"):
            raise VersionError(f"patch changes {p}; only .code is supported")
        else:
            src_file = ROMFS / p.lstrip("/")
        src = src_file.read_bytes() if src_file.is_file() else b""
        if e["src_size"] and sha(src) != e["src_sha256"]:
            raise VersionError(f"{p}: your extracted file is not the retail one this patch expects")
        if e["src_dec"] == "blz":
            src = RETAIL_CODE.read_bytes() if p == "exefs:.code" else blz.decompress(src)
        dec = _apply_delta(src, data[e["off"]:e["off"] + e["len"]], e["dst_dec_size"])
        if p == "exefs:.code":
            code = dec
            continue
        if e["dst_enc"] == "raw":
            out = dec
        elif e["dst_enc"] == "blz":
            out = blz.compress(dec)
        elif e["dst_enc"] == "paca":
            out = dec[:8] + blz.compress(dec[8:])
        else:
            raise VersionError(f"{p}: unknown encoding {e['dst_enc']}")
        if sha(out) != e["dst_sha256"]:
            raise VersionError(f"{p}: rebuilt file does not match the patch's checksum")
        files[p] = out
    info = {"kind": "dq11patch", "name": header.get("name"), "patch_version": header.get("version")}
    return files, code, info


def _layeredfs_entries(names: list[str]) -> tuple[str | None, str | None]:
    for n in names:
        m = re.match(r"^(.*?luma/titles/[0-9A-Fa-f]{16}/)", n.replace("\\", "/"))
        if m:
            return m.group(1), None
    return None, None


def read_layeredfs(path: Path) -> tuple[dict[str, bytes], bytes | None, dict]:
    files: dict[str, bytes] = {}
    code = None
    if path.is_dir():
        items = {p.relative_to(path).as_posix(): p for p in path.rglob("*") if p.is_file()}
        read = lambda n: items[n].read_bytes()  # noqa: E731
        names = list(items)
    else:
        z = zipfile.ZipFile(path)
        names = [n for n in z.namelist() if not n.endswith("/")]
        read = z.read
    prefix, _ = _layeredfs_entries(names)
    if prefix is None:
        raise VersionError(f"{path}: no luma/titles/<title id>/ folder")
    for n in names:
        n2 = n.replace("\\", "/")
        if not n2.startswith(prefix):
            continue
        rest = n2[len(prefix):]
        if rest.startswith("romfs/"):
            files["/" + rest[len("romfs/"):]] = read(n)
        elif rest == "code.bin":
            code = read(n)
        elif rest == "code.ips":
            from tools.export_mod import apply_ips
            code = apply_ips(RETAIL_CODE.read_bytes(), read(n))
    return files, code, {"kind": "layeredfs"}


def read_3ds(path: Path) -> tuple[dict[str, bytes], bytes | None, dict]:
    _translate_import()
    from dq11tool.ctr.formats import open_image
    blz = _blz()
    f, _ncsd, ncch = open_image(str(path))
    files = {}
    try:
        romfs = ncch.romfs()
        for rf in romfs.files:
            mine = ROMFS / rf.path.lstrip("/")
            if mine.is_file() and mine.stat().st_size == rf.size:
                data = romfs.read_file(rf)
                if sha(data) == sha_file(mine):
                    continue
            else:
                data = romfs.read_file(rf)
            files[rf.path] = data
        code = ncch.exefs().read(".code")
        if len(code) != RETAIL_CODE.stat().st_size:
            code = blz.decompress(code)
    finally:
        f.close()
    return files, code, {"kind": "3ds"}


def read_source(path: Path) -> tuple[dict[str, bytes], bytes | None, dict]:
    if not path.exists():
        raise VersionError(f"patch source not found: {path}")
    low = path.name.lower()
    if low.endswith(".dq11patch"):
        files, code, info = read_dq11patch(path)
    elif low.endswith((".3ds", ".cci")):
        files, code, info = read_3ds(path)
    else:
        files, code, info = read_layeredfs(path)
    # keep only real changes against the retail files
    kept = {}
    for p, data in files.items():
        mine = ROMFS / p.lstrip("/")
        if not mine.is_file():
            raise VersionError(f"{p}: new RomFS files cannot be added (LayeredFS keeps the retail file table)")
        if sha_file(mine) != sha(data):
            kept[p] = data
    if code is not None and code == RETAIL_CODE.read_bytes():
        code = None
    info["source"] = str(path)
    info["source_sha256"] = sha_file(path) if path.is_file() else None
    if path.is_file():
        st = path.stat()
        info["source_size"] = st.st_size
        info["source_mtime"] = int(st.st_mtime)
    return kept, code, info


# --------------------------------------------------------------------------- deriving
def _safe_rel(name: str) -> Path:
    p = Path(name.lstrip("/"))
    parts = [x for x in p.parts if x not in ("", ".", "..")]
    return Path(*parts) if parts else Path("unnamed")


class Changes:
    """rel path (project-relative, posix) -> new bytes or None (removed)."""

    def __init__(self):
        self.new: dict[str, bytes | None] = {}

    def set(self, rel: Path | str, data: bytes | None) -> None:
        rel = Path(rel).as_posix()
        old = ROOT / rel
        if data is None and not old.exists():
            return
        if data is not None and old.is_file() and sha_file(old) == sha(data):
            self.new.pop(rel, None)
            return
        self.new[rel] = data


def _pack_members(data: bytes) -> tuple[dict, dict]:
    from tools import pack as pack_tool
    p = pack_tool.Pack.parse(data)
    members = {}
    for e in p.entries:
        members[_safe_rel(e.name).as_posix()] = e.data
    return p, members


def derive_game_data(files: dict[str, bytes], ch: Changes, report: dict) -> list[str]:
    """RomFS files -> romfs + pack members + arc members. Returns changed member paths."""
    members_changed: list[str] = []
    for p, data in sorted(files.items()):
        rel = _safe_rel(p)
        ch.set(Path("game_data/romfs") / rel, data)
        if not p.endswith(".pack"):
            members_changed.append((Path("game_data/romfs") / rel).as_posix())
            continue
        stem = rel.with_suffix("")
        target = Path("game_data/packs") / stem
        old_p, old_m = _pack_members((ROMFS / rel).read_bytes())
        new_p, new_m = _pack_members(data)
        for name in sorted(set(old_m) | set(new_m)):
            if old_m.get(name) == new_m.get(name):
                continue
            member_rel = target / name
            ch.set(member_rel, new_m.get(name))
            members_changed.append(member_rel.as_posix())
            if name.endswith(".arc"):
                derive_arc(member_rel, old_m.get(name), new_m.get(name), ch)
        meta_file = ROOT / target / "_pack.json"
        meta = _read_json(meta_file, None)
        if meta is not None:
            meta.update(size=len(data), compressed=new_p.compressed, members=len(new_p.entries))
            ch.set(target / "_pack.json", (json.dumps(meta, indent=2)).encode("utf-8"))
    report["members_changed"] = len(members_changed)
    return members_changed


def derive_arc(member_rel: Path, old: bytes | None, new: bytes | None, ch: Changes) -> None:
    _translate_import()
    from dq11tool.darc import Sarc
    rel = member_rel.relative_to("game_data/packs")
    target = Path("game_data/arcs") / rel.with_suffix("")

    def explode(raw):
        if raw is None:
            return {}
        s = Sarc.parse(raw)
        return {_safe_rel(n.name).as_posix(): raw[s.data_offset + n.start:s.data_offset + n.end] for n in s.nodes}

    a, b = explode(old), explode(new)
    for name in sorted(set(a) | set(b)):
        if a.get(name) != b.get(name):
            ch.set(target / name, b.get(name))
    meta_file = ROOT / target / "_arc.json"
    meta = _read_json(meta_file, None)
    if meta is not None and new is not None:
        meta["members"] = [{"name": n, "size": len(d), "magic": d[:4].hex(),
                            "path": (target / n).as_posix()} for n, d in b.items()]
        ch.set(target / "_arc.json", json.dumps(meta, indent=2).encode("utf-8"))


def _collect(tmp: Path, ch: Changes) -> None:
    for f in tmp.rglob("*"):
        if f.is_file():
            ch.set(f.relative_to(tmp), f.read_bytes())


def derive_assets(member_paths: list[str], tmp: Path, report: dict) -> None:
    """Run the project's converters on the changed members (already in place) into `tmp`."""
    from tools import convert_assets as ca
    errors = []
    done = {}

    def note(kind):
        done[kind] = done.get(kind, 0) + 1

    arc_members = [p for p in member_paths if p.startswith("game_data/arcs/")]
    for rel in member_paths + arc_members:
        src = ROOT / rel
        if not src.is_file():
            continue
        ext = src.suffix.lower()
        drel = Path(rel).relative_to("game_data")
        try:
            if ext == ".bflim":
                from tools.texture_tool import bflim_to_png
                bflim_to_png(src.read_bytes(), (tmp / "game_assets/textures" / drel).with_suffix(".png"))
                note("textures")
            elif ext in (".bflyt", ".bflan"):
                from tools.layout_tool import parse_bflan, parse_bflyt
                raw = src.read_bytes()
                data = parse_bflyt(raw) if ext == ".bflyt" else parse_bflan(raw)
                out = (tmp / "game_assets/layouts" / drel).with_suffix(drel.suffix + ".json")
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
                note("layouts")
            elif ext == ".cnut":
                from tools import sqbin
                from tools import squirrel_decompile as sd
                raw = src.read_bytes()
                out = (tmp / "game_assets/scripts" / drel).with_suffix(".nut")
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(sqbin.disasm(sqbin.parse(raw)), encoding="utf-8")
                text, _stats = sd.decompile_bytes(raw, drel.as_posix())
                out2 = (tmp / "game_assets/scripts" / drel).with_suffix("").with_suffix(sd.SUFFIX)
                out2.write_text(text, encoding="utf-8", newline="\n")
                note("scripts")
            elif ext == ".bxon":
                from tools import bxon
                from tools.bxon_struct import StructDecoder
                raw = src.read_bytes()
                table = bxon.Bxon.parse(raw)
                if table.type_name in {"Level3DBin", "Level2DBin", "LevelDMapBin"}:
                    payload = table.to_json()
                    report.setdefault("warnings", []).append(f"{rel}: level data changed; maps/ not regenerated")
                else:
                    payload = json.dumps(StructDecoder(raw).decode(), indent=2, ensure_ascii=False)
                out = (tmp / "game_assets/tables" / drel).with_suffix(".json")
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(payload, encoding="utf-8")
                note("tables")
            elif ext == ".bch":
                saved = ca.ASSETS_DIR
                ca.ASSETS_DIR = tmp / "game_assets"
                try:
                    ca._convert_model(src)
                finally:
                    ca.ASSETS_DIR = saved
                note("models")
            elif ext == ".bffnt":
                from tools import font_tool
                font_tool.export(src, tmp / "game_assets/fonts")
                note("fonts")
        except Exception as exc:  # one bad file must not stop the import
            errors.append(f"{rel}: {type(exc).__name__}: {exc}")
    report["assets"] = done
    if errors:
        report.setdefault("warnings", []).extend(errors[:200])


