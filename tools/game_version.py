def import_version(name: str, source: Path | None, label: str | None, use_after: bool) -> dict:
    if name == ORIGINAL or not re.fullmatch(r"[a-z0-9_]+", name):
        raise VersionError("version names are lower-case letters, digits and _ (not 'original')")
    cfg = sources()
    entry = dict(cfg.get(name, {}))
    if source is not None:
        entry["source"] = str(source.resolve())
    if label:
        entry["label"] = label
    if not entry.get("source"):
        raise VersionError(f"no source for {name!r}; pass --from")
    entry.setdefault("label", name)
    repo = Path(entry.get("repo") or TRANSLATE)
    previous = active()
    if previous != ORIGINAL or state().get("switching_to"):
        print(f"switching to 'original' first (was {previous!r})")
        switch(ORIGINAL)
    print(f"reading {entry['source']} ...")
    files, code, info = read_source(Path(entry["source"]))
    print(f"  {len(files)} RomFS file(s) changed, code.bin {'changed' if code else 'unchanged'}")
    report: dict = {}
    ch = Changes()
    members = derive_game_data(files, ch, report)
    print(f"  {report['members_changed']} pack/arc member(s) changed")

    # put the game_data level in place, derive assets from it, then restore the retail files
    base_files = {rel: sha_file(ROOT / rel) for rel in ch.new}
    staged = {rel: (put_blob(d) if d is not None else None) for rel, d in ch.new.items()}
    original_m = load_manifest(ORIGINAL)
    old_m = _read_json(manifest_path(name), {})
    for rel, d in base_files.items():
        original_m["files"].setdefault(rel, put_blob((ROOT / rel).read_bytes()) if d else None)
    _write_json(manifest_path(ORIGINAL), original_m)
    _write_json(STATE, {"active": ORIGINAL, "switching_to": name, "since": _now(), "importing": True})
    try:
        for rel, digest in staged.items():
            _place(rel, digest)
        with tempfile.TemporaryDirectory(prefix="_tmp_assets_", dir=VERSIONS) as td:
            td = Path(td)
            print("  converting changed assets ...")
            derive_assets(members + [m for m in ch.new if m.startswith("game_data/arcs/")], td, report)
            print("  exporting text banks ...")
            derive_text(td, report)
            ch2 = Changes()
            for rel in base_files:               # retail game_data back in place

                _place(rel, original_m["files"][rel])
            _collect(td, ch2)
    except BaseException:
        for rel in base_files:
            _place(rel, original_m["files"][rel])
        _write_json(STATE, {"active": ORIGINAL, "since": _now()})
        raise
    _write_json(STATE, {"active": ORIGINAL, "since": _now()})
    ch.new.update(ch2.new)

    code_meta = None
    if code is not None:
        print("  analysing the native code changes ...")
        vdir = VERSIONS / name / "code"
        vdir.mkdir(parents=True, exist_ok=True)
        (vdir / "code.decompressed.bin").write_bytes(code)
        changes = analyse_code(code, repo)
        _write_json(VERSIONS / name / "code_changes.json", changes)
        print("  disassembling (asm/) ...")
        derive_asm(code, ch, report)
        code_meta = {"sha256": sha(code), "size": len(code),
                     "functions": len(changes["functions"]), "caves": len(changes["caves"]),
                     "data_runs": len(changes["data"]), "changed_bytes": changes["changed_bytes"]}

    files_m = {}
    for rel, d in ch.new.items():
        files_m[rel] = put_blob(d) if d is not None else None
        if rel not in original_m["files"]:
            p = ROOT / rel
            original_m["files"][rel] = put_blob(p.read_bytes()) if p.is_file() else None
    _write_json(manifest_path(ORIGINAL), original_m)
    manifest = {
        "name": name,
        "label": entry["label"],
        "imported_at": _now(),
        "source": {**info, "path": entry["source"]},
        "romfs_changed": sorted(files),
        "code": code_meta,
        "report": report,
        "files": dict(sorted(files_m.items())),
    }
    if old_m:
        gone = set(old_m.get("files", {})) - set(files_m)
        manifest["dropped_since_last_import"] = len(gone)
    _write_json(manifest_path(name), manifest)
    cfg[name] = entry
    _write_json(SOURCES, {k: v for k, v in cfg.items()})
    print(f"imported {name!r}: {len(files_m):,} tracked file(s)"
          + (f", {code_meta['functions']} function(s) + {code_meta['caves']} cave(s) changed" if code_meta else ""))
    for w in report.get("warnings", [])[:10]:
        print(f"  warning: {w}")
    gc_store()
    if use_after or previous == name:
        switch(name)
    return manifest


def gc_store() -> None:
    keep = set()
    for n in installed():
        keep |= {d for d in load_manifest(n)["files"].values() if d}
    if not STORE.is_dir():
        return
    for p in STORE.rglob("*"):
        if p.is_file() and p.name not in keep:
            p.unlink()


