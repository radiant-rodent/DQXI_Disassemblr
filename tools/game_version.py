def derive_asm(code: bytes, ch: Changes, report: dict) -> None:
    """Disassemble retail and patched code with the project's disassembler; keep differing files."""
    import subprocess
    with tempfile.TemporaryDirectory(prefix="_tmp_asm_", dir=VERSIONS) as td:
        td = Path(td)
        (td / "patched.bin").write_bytes(code)
        for name, src in (("a", RETAIL_CODE), ("b", td / "patched.bin")):
            r = subprocess.run([sys.executable, str(ROOT / "tools" / "disasm.py"), str(src), str(td / name)],
                               cwd=ROOT, capture_output=True, text=True)
            if r.returncode:
                report.setdefault("warnings", []).append(f"disasm failed: {r.stderr[-400:]}")
                return
        n = 0
        for f in (td / "b").rglob("*.s"):
            rel = f.relative_to(td / "b")
            a = td / "a" / rel
            if a.is_file() and a.read_bytes() == f.read_bytes():
                continue
            ch.set(Path("asm") / rel, f.read_bytes())
            n += 1
        # page padding after .text/.rodata/.data: the translation keeps its code caves and moved
        # strings there; tools.build zero-fills it unless asm/pad/<segment>_tail.s exists
        for seg, (start, size) in PAD_SEGMENTS.items():
            blob = code[start - BASE:start - BASE + size]
            rel = Path("asm") / "pad" / f"{seg}_tail.s"
            if blob.strip(b"\0"):
                ch.set(rel, pad_source(seg, start, blob).encode("utf-8"))
                n += 1
        report["asm_files"] = n


PAD_SEGMENTS = {"text": (0x0072403C, 4036), "rodata": (0x0079AA18, 1512), "data": (0x007C2D24, 732)}


def pad_source(seg: str, start: int, blob: bytes) -> str:
    """Bit-exact tagged listing of one padding region (the format tools.build reads)."""
    import capstone
    md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_ARM)
    lines = [f"@ {seg} page padding 0x{start:08X}-0x{start + len(blob):08X}: written by the game version's patch",
             "@ (tools/game_version.py); the /* address: bytes */ tags are what tools.build assembles", ""]
    for off in range(0, len(blob), 4):
        word = blob[off:off + 4]
        addr = start + off
        text = f".word   0x{int.from_bytes(word, 'little'):08X}"
        if seg == "text" and word != b"\0\0\0\0":
            insn = next(md.disasm(word, addr), None)
            if insn is not None:
                text = f"{insn.mnemonic:<8} {insn.op_str}".rstrip()
        lines.append(f"    /* 0x{addr:08X}: {word.hex()} */  {text}")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- code analysis
def _functions() -> list[dict]:
    path = ROOT / "decomp" / "ghidra" / "functions_merged.jsonl"
    out = []
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            try:
                v = json.loads(line)
                out.append({"address": int(v["address"], 16), "size": int(v.get("size") or 0),
                            "name": v.get("name") or f"func_{v['address']}", "mode": v.get("mode", "arm"),
                            "file": v.get("file", "")})
            except (ValueError, KeyError, json.JSONDecodeError):
                continue
    out.sort(key=lambda f: f["address"])
    return out


def _segment(addr: int) -> str:
    if addr < 0x0072403C:
        return "text"
    if addr < 0x00725000:
        return "text_tail"          # free page padding after .text: the translation's code caves
    if addr < 0x0079AA18:
        return "rodata"
    if addr < 0x0079B000:
        return "rodata_tail"
    return "data"


def _runs(a: bytes, b: bytes, gap: int = 8) -> list[tuple[int, int]]:
    runs = []
    i, n = 0, len(a)
    while i < n:
        if a[i] == b[i]:
            # skip fast over equal 4 KiB blocks
            j = i & ~0xFFF
            if a[j:j + 0x1000] == b[j:j + 0x1000]:
                i = j + 0x1000
                continue
            i += 1
            continue
        s = i
        last = i
        while i < n and i - last <= gap:
            if a[i] != b[i]:
                last = i
            i += 1
        runs.append((s, last + 1))
    return runs


def _doc_notes(repo: Path) -> tuple[list[tuple[int, int, str]], list[tuple[str, str]], dict[int, str]]:
    """Cave map, address-mentioning doc lines and per-instruction reasons from the translation repo."""
    caves, lines, why = [], [], {}
    guide = repo / "docs" / "AGENT_GUIDE.md"
    if guide.is_file():
        for line in guide.read_text(encoding="utf-8", errors="replace").splitlines():
            m = re.match(r"^\|\s*(0x[0-9A-Fa-f]+)\s*(?:/\s*(0x[0-9A-Fa-f]+))?\s*(?:-\s*(0x[0-9A-Fa-f]+))?\s*\|\s*(.+?)\s*\|\s*$", line)
            if m and int(m.group(1), 16) >= 0x72403C:
                start = int(m.group(1), 16)
                caves.append((start, int(m.group(3), 16) if m.group(3) else None, m.group(4)))
                continue
            if re.search(r"0x[0-9A-Fa-f]{5,6}", line):
                lines.append(("AGENT_GUIDE.md", line.strip()))
    codefix = repo / "dq11tool" / "codefix.py"
    if codefix.is_file():
        try:
            tree = ast.parse(codefix.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "INSTRUCTIONS" for t in node.targets):
                    for row in ast.literal_eval(node.value):
                        why[row[0] + BASE] = row[3]
        except (SyntaxError, ValueError, IndexError):
            pass
    # module docstrings of the code patchers name their hook addresses too
    for mod in sorted((repo / "dq11tool").glob("*.py")):
        try:
            doc = ast.get_docstring(ast.parse(mod.read_text(encoding="utf-8"))) or ""
        except (SyntaxError, UnicodeDecodeError):
            continue
        for line in doc.splitlines():
            if re.search(r"0x[0-9A-Fa-f]{5,6}", line):
                lines.append((f"dq11tool/{mod.name}", line.strip()))
    # a row with a start address only runs to the next row
    caves.sort(key=lambda c: c[0])
    caves = [(a, b if b is not None else (caves[i + 1][0] if i + 1 < len(caves) else 0x725000), t)
             for i, (a, b, t) in enumerate(caves)]
    return caves, lines, why


def _mentions(lines, lo: int, hi: int) -> list[str]:
    out = []
    for src, line in lines:
        for h in re.findall(r"0x([0-9A-Fa-f]{5,6})\b", line):
            v = int(h, 16)
            for addr in (v, v + BASE):     # docs use both file offsets and addresses
                if lo <= addr < hi:
                    out.append(f"{src}: {line}")
                    break
            else:
                continue
            break
    return list(dict.fromkeys(out))[:8]


def disasm_range(code: bytes, addr: int, size: int, mode: str = "arm") -> list[str]:
    import capstone
    md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_THUMB if mode == "thumb" else capstone.CS_MODE_ARM)
    off = addr - BASE
    blob = code[off:off + size]
    out, pos = [], 0
    step = 2 if mode == "thumb" else 4
    while pos < len(blob):
        got = False
        for insn in md.disasm(blob[pos:], addr + pos):
            out.append(f"{insn.address:08X}  {insn.bytes.hex():<8}  {insn.mnemonic} {insn.op_str}".rstrip())
            pos += insn.size
            got = True
        if pos < len(blob):
            word = blob[pos:pos + step]
            out.append(f"{addr + pos:08X}  {word.hex():<8}  .word 0x{int.from_bytes(word, 'little'):0{len(word) * 2}X}")
            pos += step
        if not got and pos >= len(blob):
            break
    return out


def _utf16_preview(data: bytes) -> str:
    """The run as UTF-16 text when it looks like text (moved / translated strings), else ''."""
    if len(data) % 2:
        data = data[:-1]
    text = data.decode("utf-16-le", errors="replace")

    def texty(ch: str) -> bool:
        return (ch in "\0\n" or " " <= ch <= "~" or "　" <= ch <= "ヿ" or "一" <= ch <= "鿿"
                or "＀" <= ch <= "￯" or "‐" <= ch <= "…")

    if not text or sum(map(texty, text)) < 0.9 * len(text):
        return ""
    return " | ".join(x for x in text.split("\0") if x)[:160]


def analyse_code(code: bytes, repo: Path) -> dict:
    orig = RETAIL_CODE.read_bytes()
    if len(code) != len(orig):
        raise VersionError("patched code.bin has a different size; code-set sizes are not supported")
    funcs = _functions()
    starts = [f["address"] for f in funcs]
    import bisect
    caves, doc_lines, why = _doc_notes(repo)
    runs = _runs(orig, code)
    functions: dict[int, dict] = {}
    cave_entries: dict[int, dict] = {}
    data_runs = []

    def func_at(addr):
        i = bisect.bisect_right(starts, addr) - 1
        if i >= 0 and funcs[i]["address"] <= addr < funcs[i]["address"] + max(funcs[i]["size"], 4):
            return funcs[i]
        return None

    for s, e in runs:
        addr = BASE + s
        seg = _segment(addr)
        if seg == "text":
            pos = addr
            while pos < BASE + e:
                f = func_at(pos)
                if f is None:
                    # code changed outside any known function: treat like a cave
                    entry = cave_entries.setdefault(pos & ~3, {"address": pos & ~3, "end": pos & ~3})
                    entry["end"] = max(entry["end"], BASE + e)
                    break
                fe = functions.setdefault(f["address"], {**f, "kind": "modified", "ranges": []})
                hi = min(BASE + e, f["address"] + max(f["size"], 4))
                fe["ranges"].append([pos, hi])
                pos = hi
        elif seg == "text_tail":
            entry = cave_entries.setdefault(addr & ~3, {"address": addr & ~3, "end": addr})
            entry["end"] = max(entry["end"], BASE + e)
        else:
            data_runs.append({"address": addr, "size": e - s, "segment": seg,
                              "old": _utf16_preview(orig[s & ~1:e + 1]), "new": _utf16_preview(code[s & ~1:e + 1])})

    # caves: cut along the translation's documented cave map when it has one
    cave_list = []
    merged = sorted(cave_entries.values(), key=lambda c: c["address"])
    for c in merged:
        lo, hi = c["address"], (c["end"] + 3) & ~3
        cuts = sorted({lo, hi} | {a for a, _b, _t in caves if lo < a < hi} | {b for _a, b, _t in caves if lo < b < hi})
        for a, b in zip(cuts, cuts[1:]):
            label = next((t for ca_, cb, t in caves if ca_ <= a < cb), "")
            module = re.search(r"`?([a-z_]+)(?:\.py)?`?", label.split("(")[0]) if label else None
            mod = module.group(1) if module else ("cave" if _segment(a) == "text_tail" else "patch")
            cave_list.append({"address": a, "size": b - a, "name": f"EN_{mod}_{a:08X}", "mode": "arm",
                              "kind": "cave", "note": label})
    for c in cave_list:
        c["original"] = []
        c["patched"] = disasm_range(code, c["address"], c["size"])
        c["notes"] = ([f"cave map: {c['note']}"] if c["note"] else []) + _mentions(doc_lines, c["address"], c["address"] + c["size"])

    cave_ranges = [(c["address"], c["address"] + c["size"], c["name"]) for c in cave_list]
    out_funcs = []
    for f in sorted(functions.values(), key=lambda f: f["address"]):
        size = max(f["size"], 4)
        f["original"] = disasm_range(orig, f["address"], size, f["mode"])
        f["patched"] = disasm_range(code, f["address"], size, f["mode"])
        hooks = []
        for line in f["patched"]:
            m = re.search(r"\b(?:b|bl|blx|b[a-z]{2})\s+#0x([0-9a-f]+)", line)
            if m:
                tgt = int(m.group(1), 16)
                for lo, hi, name in cave_ranges:
                    if lo <= tgt < hi:
                        hooks.append({"at": int(line[:8], 16), "target": tgt, "cave": name})
        if hooks:
            f["kind"] = "hook"
            f["hooks"] = hooks
        f["changed_bytes"] = sum(b - a for a, b in f["ranges"])
        reasons = [why[a] for a in sorted(why) if f["address"] <= a < f["address"] + size]
        f["notes"] = [f"codefix.py: {r}" for r in reasons] + _mentions(doc_lines, f["address"], f["address"] + size)
        out_funcs.append(f)
    for c in cave_list:
        c["called_from"] = [{"function": f["name"], "address": f["address"], "at": h["at"]}
                            for f in out_funcs for h in f.get("hooks", []) if h["cave"] == c["name"]]
    return {
        "generated_at": _now(),
        "changed_bytes": sum(e - s for s, e in runs),
        "functions": out_funcs,
        "caves": cave_list,
        "data": data_runs,
    }


